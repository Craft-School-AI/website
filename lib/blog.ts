/**
 * Блок статьи. Обычная строка = абзац (обратная совместимость со старыми
 * постами). Объект — структурный блок: заголовок, нумерованные шаги, список,
 * заметка-выноска или интерактивный чеклист. Внутри текста поддерживается
 * лёгкая разметка:
 *   [подпись](ссылка)  — ссылка,  `код` — моноширинный текст,  **жирный**.
 */
export type BlogBlock =
  | { type: 'paragraph'; text: string }
  | { type: 'heading'; level?: 2 | 3; text: string }
  | { type: 'steps'; items: string[] }
  | { type: 'list'; items: string[] }
  | { type: 'note'; text: string }
  | { type: 'checklist'; id: string; items: string[] };

export type BlogContent = string | BlogBlock;

